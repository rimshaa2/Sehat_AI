import {
  SafeAreaView,
  View,
  Text,
  TouchableOpacity,
  ScrollView,
  FlatList,
  ActivityIndicator,
  RefreshControl,
  Share,
  Alert,
  ListRenderItem,
  StyleSheet,
  Dimensions,
} from 'react-native';
